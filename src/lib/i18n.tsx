type Key = keyof (typeof dict)["es"];

const I18nContext = createContext<{ locale: Locale; t: (k: Key) => string; setLocale: (l: Locale) => void }>({
  locale: "es",
  t: (k) => k,
  setLocale: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("es");
  useEffect(() => {
    const saved = typeof window !== "undefined" ? (window.localStorage.getItem("labsbnb.locale") as Locale | null) : null;
    if (saved === "en" || saved === "es") setLocaleState(saved);
  }, []);
  const setLocale = (l: Locale) => {
    setLocaleState(l);
    if (typeof window !== "undefined") window.localStorage.setItem("labsbnb.locale", l);
  };
  const t = (k: Key) => dict[locale][k] ?? k;
  return <I18nContext.Provider value={{ locale, t, setLocale }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
